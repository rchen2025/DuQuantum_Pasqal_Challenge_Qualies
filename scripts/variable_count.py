#!/usr/bin/env python3
"""Derive 4.1 variable-count table for every registered formulation x tier.

    python scripts/variable_count.py                 # print the Markdown table
    python scripts/variable_count.py --check instances/   # also assert n_vars == count_vars on real instances
    python scripts/variable_count.py --write-md      # paste the table into docs/MODEL_WRITEUP.md between
                                                     # <!-- VARIABLE_COUNT_TABLE --> and <!-- /VARIABLE_COUNT_TABLE -->

Row order: assignment-only, textbook (+ binary-encoded slack), then every other
registered formulation ("ours", Gate 1).  Numbers are never typed by hand:
they come from ``Formulation.count_vars(N, K, Q)`` and ``TIERS``.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Dict, List, Type

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from cvrp import common  # noqa: E402
from cvrp.common import TIERS, Formulation  # noqa: E402
from cvrp.model import registered_formulations  # noqa: E402

MAX_ATOMS = 80          # brief §3.1 (also asserted against pulser by scripts/device_limits.py)
TIER_ORDER = ["S", "M", "L"]
FIRST_ROWS = ["assignment-only", "textbook"]
MD_PATH = ROOT / "docs" / "MODEL_WRITEUP.md"
MARK_OPEN, MARK_CLOSE = "<!-- VARIABLE_COUNT_TABLE -->", "<!-- /VARIABLE_COUNT_TABLE -->"


def ordered_formulations() -> List[Type[Formulation]]:
    reg = registered_formulations()
    names = [n for n in FIRST_ROWS if n in reg] + sorted(n for n in reg if n not in FIRST_ROWS)
    return [reg[n] for n in names]


def row_for(cls: Type[Formulation]) -> Dict[str, object]:
    counts = {t: cls.count_vars(TIERS[t]["N"], TIERS[t]["K"], TIERS[t]["Q"]) for t in TIER_ORDER}
    label = getattr(cls, "table_label", "") or cls.name
    if cls.name not in FIRST_ROWS:
        label = f"{label} (ours: `{cls.name}`)"
    formula = getattr(cls, "var_formula", "") or "see `count_vars`"
    fits = "/".join(("yes (=cap)" if counts[t] == MAX_ATOMS else "yes") if counts[t] <= MAX_ATOMS else "no"
                    for t in TIER_ORDER)
    return {"label": label, "formula": formula, "counts": counts, "fits": fits}


def markdown_table() -> str:
    lines = [
        "| Encoding | Variable count (formula) | S | M | L | Fits in 80 atoms? (S/M/L) |",
        "|---|---|---|---|---|---|",
    ]
    for cls in ordered_formulations():
        r = row_for(cls)
        c = r["counts"]
        lines.append(f"| {r['label']} | {r['formula']} | {c['S']} | {c['M']} | {c['L']} | {r['fits']} |")
    if not any(cls.name not in FIRST_ROWS for cls in ordered_formulations()):
        lines.append("| Your formulation (Gate 1: register it in `cvrp/formulations/` and re-run) | … | … | … | … | … |")
    lines.append("")
    lines.append(f"Tiers (brief Table 1): " + "; ".join(
        f"{t}: N={TIERS[t]['N']}, K={TIERS[t]['K']}, Q={TIERS[t]['Q']}" for t in TIER_ORDER)
        + f". Atom budget {MAX_ATOMS}. Slack bits per vehicle B = ⌈log2(Q+1)⌉ = "
        + ", ".join(f"{t}: {_slack_bits(TIERS[t]['Q'])}" for t in TIER_ORDER)
        + ". Generated by `python scripts/variable_count.py --write-md`.")
    return "\n".join(lines)


def _slack_bits(Q: int) -> int:
    import math
    return int(math.ceil(math.log2(Q + 1)))


def check_instances(folder: Path) -> int:
    insts = common.load_instances(folder)
    if not insts:
        print(f"no instance JSON in {folder}")
        return 1
    bad = 0
    for inst in insts:
        for cls in ordered_formulations():
            f = cls(inst)
            expect = cls.count_vars(inst.N, inst.K, inst.Q)
            ok = f.n_vars == expect
            bad += not ok
            print(f"{'OK  ' if ok else 'FAIL'} {inst.name:<20} {cls.name:<18} n_vars={f.n_vars} count_vars={expect}")
    return 1 if bad else 0


def write_md(table: str, path: Path = MD_PATH) -> None:
    text = path.read_text()
    pattern = re.compile(re.escape(MARK_OPEN) + r".*?" + re.escape(MARK_CLOSE), re.S)
    if not pattern.search(text):
        raise SystemExit(f"{path} has no {MARK_OPEN} ... {MARK_CLOSE} block")
    new = f"{MARK_OPEN}\n{table}\n{MARK_CLOSE}"
    path.write_text(pattern.sub(lambda _m: new, text))
    print(f"wrote table into {path}")


def main(argv: List[str]) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--check", metavar="INSTANCES_DIR", help="assert n_vars == count_vars on every instance JSON")
    p.add_argument("--write-md", action="store_true", help=f"replace the marked block in {MD_PATH.relative_to(ROOT)}")
    a = p.parse_args(argv)
    table = markdown_table()
    print(table)
    rc = 0
    if a.check:
        rc = check_instances(Path(a.check))
    if a.write_md:
        write_md(table)
    return rc


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
