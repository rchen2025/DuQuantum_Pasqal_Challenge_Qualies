#!/usr/bin/env python
"""Three landscapes over ALL one-hot assignments (K^N): original model, target QUBO, realised register.

    python scripts/landscapes.py instances/M_seed00.json [...] --out docs/checks/landscapes.md

Separates the three places where tier-M quality can be lost (handoff after report_1850, Priority 2):
  (1) original constrained model  f(a)  = closeness objective, capacity-feasible assignments only;
  (2) target penalized QUBO        E_Q(x) = x^T Q x + offset  with the load-balance term, on one-hot strings;
  (3) realised register            E_dev(x) = -delta_f sum x + sum_{a<b} U_ab x_a x_b  (cached polygon register).
For each instance: the model optimum (witness, #optima mod vehicle relabelling), the QUBO argmin over one-hot
strings (feasible? its f, its gap), the device argmin over one-hot strings (same), the model optimum's rank under
E_Q and under E_dev (ties counted explicitly; vehicle relabellings of the same clustering identified), the best
*feasible* one-hot string under E_dev and its model gap / exact routed cost, and whether P(model gap <= 5 %) can
differ from P(model optimum) (is there any feasible assignment with 0 < gap <= 5 %?).  Enumerates K^N assignments
(59 049 on M; S is 16) — this certifies statements on the one-hot SUBSPACE only, never over all 2^(NK) bitstrings.
"""
from __future__ import annotations

import argparse
import itertools
import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from cvrp.common import Instance, clustering_of, gap_percent, route_exactly  # noqa: E402
from cvrp.embed import Embedding  # noqa: E402
from cvrp.model import get_formulation  # noqa: E402

TOL = 1e-9


def all_assignments(N: int, K: int) -> np.ndarray:
    return np.array(list(itertools.product(range(K), repeat=N)), dtype=np.int8)


def rank_of(values: np.ndarray, idx: np.ndarray) -> tuple[int, int]:
    """1-based rank of the best of rows `idx` under `values` (ascending) and the number of strictly better rows."""
    best = values[idx].min()
    n_better = int((values < best - TOL).sum())
    return n_better + 1, n_better


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("instances", nargs="+")
    ap.add_argument("--formulation", default="onehot-ub")
    ap.add_argument("--embeddings", default="embeddings")
    ap.add_argument("--out", default="docs/checks/landscapes.md")
    a = ap.parse_args(argv)
    lines = ["# Three landscapes over all one-hot assignments (generated by `scripts/landscapes.py`)", "",
             "Model = closeness objective on capacity-feasible assignments; QUBO = `onehot-ub` energy with the "
             "load-balance term; device = cached polygon register at Ω = 0 with its δ_f. Ranks count strictly better "
             "one-hot strings (vehicle relabellings of one clustering are tied by construction). All statements are "
             "about the one-hot subspace (K^N strings), not about all 2^(NK) bitstrings.", ""]
    for path in a.instances:
        inst = Instance.load(ROOT / path if not Path(path).is_absolute() else path)
        f = get_formulation(a.formulation, inst)
        N, K = inst.N, inst.K
        A = all_assignments(N, K)
        X = np.zeros((len(A), N * K))
        X[np.arange(len(A))[:, None], np.arange(N)[None, :] * K + A] = 1.0
        Q, off = f.Q(), float(f.offset)
        EQ = np.einsum("bi,ij,bj->b", X, Q, X) + off
        loads = np.stack([(A == k) @ np.asarray(inst.demands, float) for k in range(K)], 1)
        feas = (loads <= inst.Q + 1e-9).all(1)
        fobj = np.array([f.objective(tuple(int(v) for v in row)) for row in A])
        fmin = fobj[feas].min()
        opt_rows = np.where(feas & (np.abs(fobj - fmin) <= TOL))[0]
        n_opt_clust = len({clustering_of(tuple(int(v) for v in A[i])) for i in opt_rows})
        # QUBO landscape
        q_arg = np.where(np.abs(EQ - EQ.min()) <= 1e-6)[0]
        q_feas = bool(feas[q_arg].all())
        q_f = fobj[q_arg].min()
        q_rank, q_better = rank_of(EQ, opt_rows)
        # device landscape
        wkey = "_".join(f"{k}={v:.6g}" for k, v in sorted(f.weights.items()))
        cands = sorted((ROOT / a.embeddings).glob(f"{inst.name}__{a.formulation}__*__polygons__seed0.json"))
        dev = None
        if cands:
            emb = Embedding.from_dict(json.loads(cands[0].read_text()))
            Edev = -emb.delta_final * X.sum(1) + 0.5 * np.einsum("bi,ij,bj->b", X, emb.U, X)
            d_arg = np.where(np.abs(Edev - Edev.min()) <= 1e-6)[0]
            d_feas = bool(feas[d_arg].all())
            d_rank, d_better = rank_of(Edev, opt_rows)
            order = np.argsort(Edev)
            best_feas_row = next(i for i in order if feas[i])
            bf_rank = int(np.where(order == best_feas_row)[0][0]) + 1
            bf_a = tuple(int(v) for v in A[best_feas_row])
            bf_gap = gap_percent(fobj[best_feas_row], fmin)
            bf_routed, _ = route_exactly(inst, bf_a)
            bf_cvrp_gap = gap_percent(bf_routed, float(inst.reference["cost"]))
            dev = dict(file=cands[0].name, delta_f=emb.delta_final, argmin_feasible=d_feas, argmin_f=float(fobj[d_arg].min()),
                       argmin_gap=gap_percent(float(fobj[d_arg].min()), fmin), rank=d_rank, better=d_better,
                       bf_rank=bf_rank, bf_gap=bf_gap, bf_cvrp_gap=bf_cvrp_gap, bf_routed=bf_routed,
                       argmin_onehot_excitations=float(X[d_arg[0]].sum()))
        # 5 % equivalence
        gaps = np.array([gap_percent(v, fmin) for v in fobj[feas]])
        n_between = int(((gaps > 1e-9) & (gaps <= 5.0)).sum())
        smallest_nonzero_gap = float(gaps[gaps > 1e-9].min()) if (gaps > 1e-9).any() else float("nan")
        lines += [f"## {inst.name} (N={N}, K={K}, {len(A)} one-hot strings, {int(feas.sum())} capacity-feasible)", "",
                  f"* **Model optimum** f* = {fmin:.4f}; {n_opt_clust} optimal clustering(s) ({len(opt_rows)} labelled strings); "
                  f"witness {list(map(int, A[opt_rows[0]]))}.",
                  f"* **Target QUBO** (λ₂ = {f.weights.get('lam2', float('nan')):.4g}, A = {f.weights.get('A', float('nan')):.4g}): argmin over one-hot strings is "
                  f"{'capacity-feasible' if q_feas else 'INFEASIBLE'} with f = {q_f:.4f} (gap {gap_percent(q_f, fmin):+.2f} %); "
                  f"model optimum at QUBO rank {q_rank} ({q_better} strictly better strings). "
                  + ("The load-balance term does **not** move the optimum." if q_better == 0 and q_feas else
                     "The load-balance term **moves** the optimum before any geometry enters."),
                  f"* **Smallest non-zero feasible model gap** = {smallest_nonzero_gap:.3f} %; feasible assignments with 0 < gap ≤ 5 %: {n_between} "
                  + ("→ P(model gap ≤ 5 %) ≡ P(model optimum) on this instance." if n_between == 0 else "→ the two probabilities can differ on this instance.")]
        if dev:
            lines += [f"* **Realised register** `{dev['file']}` (δ_f = {dev['delta_f']:.3f} rad/µs): one-hot argmin is "
                      f"{'feasible' if dev['argmin_feasible'] else 'INFEASIBLE'} (f gap {dev['argmin_gap']:+.2f} %); model optimum at device rank "
                      f"{dev['rank']} ({dev['better']} strictly better one-hot strings); best *feasible* one-hot string at device rank {dev['bf_rank']}: "
                      f"model gap {dev['bf_gap']:+.2f} %, routed exactly {dev['bf_routed']:.2f} = CVRP gap {dev['bf_cvrp_gap']:+.2f} %."]
        else:
            lines += ["* Realised register: no cached polygon register found."]
        lines += [""]
    out = ROOT / a.out
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
