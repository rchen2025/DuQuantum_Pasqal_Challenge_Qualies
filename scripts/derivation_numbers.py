#!/usr/bin/env python
"""Write the M2 embedding before/after numbers into docs/DERIVATIONS.md §5.7 from the run records
(never typed).  Block between <!-- M2_EMBEDDING_TABLE --> and <!-- /M2_EMBEDDING_TABLE -->.

    python scripts/derivation_numbers.py [--dirs out/m1 out/m2] [--backend numpy-sv]
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--dirs", nargs="+", default=["out/m1", "out/m2"])
    ap.add_argument("--backend", default="numpy-sv")
    ap.add_argument("--confirm-backend", default="qutip")
    ap.add_argument("--formulation", default="onehot-ub")
    a = ap.parse_args(argv)
    recs = []
    for d in a.dirs:
        for p in sorted((ROOT / d).glob("*.json")):
            r = json.loads(p.read_text())
            if r.get("counts") and r.get("formulation", {}).get("formulation") == a.formulation and r.get("backend") in (a.backend, a.confirm_backend, "random"):
                recs.append(r)
    rows = []
    for r in sorted(recs, key=lambda r: (r["instance"], r.get("embedder", ""), r["backend"])):
        m = r["metrics_raw"]; fid = r["embedding"]["fidelity"]; rr = r.get("realized_register", {})
        rows.append("| {inst} | {emb} | {be} | {feas:.3f} | {pm:.3f} | {pr:.3f} | {gap} | {frob:.3f} | {sub} | {res} | {rank} | {dfin:.1f} |".format(
            inst=r["instance"], emb=r.get("embedder", fid.get("embedder", "generic")), be=r["backend"], feas=m["feasible_rate"],
            pm=m["p_reach_model_optimum"], pr=m["p_reach_cvrp_reference"],
            gap=("%.1f %%" % m["best_model_gap"]) if m["best_model_gap"] is not None else "undefined",
            frob=fid["rel_frobenius_offdiag"],
            sub=("%.3f" % fid["subspace_rel_frobenius"]) if fid.get("subspace_rel_frobenius") is not None else "—",
            res=next((n.split("=")[1].split("(")[0].strip() for n in fid.get("notes", []) if "normalised residual" in n or "residual/variance" in n), "—"),
            rank=rr.get("rank_of_model_optimum", "—"), dfin=r["pulse"]["delta_final"]))
    head = ("| instance | embedder | backend | feasibility | P(reach model opt) | P(reach CVRP ref) | best model gap | "
            "rel. Frobenius (full) | subspace rel. Frob. | energy-fit residual | device rank of model optimum | δ_f (rad/µs) |\n"
            "|---|---|---|---|---|---|---|---|---|---|---|---|\n")
    block = head + "\n".join(rows) + f"\n\n(generated by `python scripts/derivation_numbers.py` from {', '.join(a.dirs)}; 500 shots, seed 0, baseline pulse; random sampler 2000 shots)\n"
    doc = ROOT / "docs/DERIVATIONS.md"
    text = doc.read_text()
    new = re.sub(r"<!-- M2_EMBEDDING_TABLE -->.*?<!-- /M2_EMBEDDING_TABLE -->",
                 "<!-- M2_EMBEDDING_TABLE -->\n" + block + "<!-- /M2_EMBEDDING_TABLE -->", text, flags=re.S)
    if new == text and "<!-- M2_EMBEDDING_TABLE -->" not in text:
        sys.exit("markers not found in DERIVATIONS.md")
    # scan tables (scripts/scan.py writes <out>/scan.md)
    for marker, path in (("M2_WEIGHT_SCAN", "out/m2_weights/scan.md"), ("M2_PULSE_SCAN", "out/m2_pulse/scan.md"),
                         ("M2_SLOW_SCAN", "out/m2_slow/scan.md")):
        f = ROOT / path
        if f.exists() and f"<!-- {marker} -->" in new:
            tbl = f.read_text().strip() + f"\n\n(generated by `python scripts/scan.py` → `{path}`; mean over the three M1 instances, per-instance P(reach model optimum) in the last column)\n"
            new = re.sub(rf"<!-- {marker} -->.*?<!-- /{marker} -->", f"<!-- {marker} -->\n" + tbl + f"<!-- /{marker} -->", new, flags=re.S)
    doc.write_text(new)
    print(block)


if __name__ == "__main__":
    main()
